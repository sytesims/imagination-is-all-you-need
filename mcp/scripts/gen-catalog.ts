/**
 * Writes src/catalog.snapshot.ts from a running API's GET /api/tools (id, name, media of every tool). The MCP server reads the live list;
 * this snapshot is only its fallback when the API is down at start. test/catalog.ts fails when it is stale.
 * Usage: OPENHIGGSFIELD_API=http://localhost:8787 npm run gen:catalog   (any backend; mock is fine)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const API = (process.env.OPENHIGGSFIELD_API || 'http://localhost:8787').replace(/\/$/, '');
const tools: any[] = await fetch(`${API}/api/tools`).then((r) => { if (!r.ok) throw new Error(`${API}/api/tools → ${r.status}`); return r.json(); });
const rows = tools.map((t) => ({ id: t.id, name: t.name, media: t.media, ...(t.listed === false ? { listed: false } : {}) })).sort((a, b) => a.id.localeCompare(b.id));
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/catalog.snapshot.ts');
fs.writeFileSync(out, `/** Generated by \`npm run gen:catalog\` from GET /api/tools. Do not edit. Fallback only: the MCP server reads the live list. */\n`
  + `export const TOOL_SNAPSHOT: { id: string; name: string; media: string; listed?: boolean }[] = [\n${rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')}\n];\n`);
console.log(`wrote ${out} (${rows.length} tools from ${API})`);
