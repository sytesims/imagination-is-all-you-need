#!/usr/bin/env node
/**
 * Generates server/src/shared/workflowSources.ts from workflows/provenance/image-grid.json.
 * The public provenance input holds only the image features' model metadata and workflow credits: the workflow each feature + model
 * pair is credited with (official Comfy template / community workflow / ours), plus the grid's model names and licences.
 * Run: node scripts/gen-workflow-sources.mjs        (writes the file)
 *      node scripts/gen-workflow-sources.mjs --check (exit 1 when the file is out of date; used by a server test)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GRID = path.join(ROOT, 'workflows/provenance/image-grid.json');
const OUT = path.join(ROOT, 'server/src/shared/workflowSources.ts');
/** Grid features we copy (grid ids). The app's feature → grid mapping lives in shared/imageFeatures.ts. */
const FEATURES = ['create-image', 'edit-image', 'inpaint', 'upscale', 'face-swap', 'character-swap', 'shots'];
/** The app's display name (2026-10-23); the grid still says OpenHiggsfield in places. */
const APP_NAME = 'Imagination Is All You Need';

export function render(grid) {
  const src = (w) => {
    if (!w || w.source === 'missing' || !w.source) return null;
    const ours = w.source === 'ours';
    const file = ours ? (/^https?:/.test(String(w.url ?? '')) ? null /* our request to a lab API, linked to its docs */ : String(w.url ?? w.name).replace(/^workflows\//, '')) : (/ours: workflows\/([\w.-]+)/.exec(w.note ?? '')?.[1] ?? null);
    return { source: w.source, name: w.name, url: ours ? (/^https?:/.test(String(w.url ?? '')) ? w.url : null) : w.url ?? null, author: ours ? APP_NAME : String(w.author ?? '').replace(/\s*\(in the official repo\)\s*$/, ''),
      licence: ours ? 'AGPL-3.0 (this repo)' : w.license ?? 'not stated', ...(file ? { file } : {}) };
  };
  const cells = {};
  for (const f of FEATURES) {
    cells[f] = {};
    for (const c of grid.cells.filter((x) => x.featureId === f && x.support !== 'no')) { const s = src(c.workflow); if (s) cells[f][c.modelId] = { ...s, support: c.support }; }
  }
  const models = Object.fromEntries(grid.models.map((m) => [m.id, { name: m.name, maker: String(m.maker ?? '').replace(/OpenHiggsfield/g, APP_NAME), openWeights: !!m.openWeights, licence: m.licence, licenceUrl: m.licenseUrl ?? null }]));
  const j = (x) => JSON.stringify(x, null, 1).replace(/\n\s*/g, ' ');
  const lines = [
    '// GENERATED by scripts/gen-workflow-sources.mjs from workflows/provenance/image-grid.json. Do not edit; edit the public provenance input and rerun the script.',
    '/** Where each image workflow comes from (step 2 of the transparency plan): per grid feature, per grid model id. Isomorphic (web imports it). */',
    "export type WorkflowSourceKind = 'official' | 'community' | 'ours';",
    '/** source: official = a Comfy-Org/workflow_templates template; community = someone else\'s published workflow; ours = a graph in this repo\'s workflows/. */',
    "export interface WorkflowSource { source: WorkflowSourceKind; name: string; url: string | null; author: string; licence: string; /** our local graph (workflows/<file>) */ file?: string; support?: string }",
    `export const GRID_GENERATED = ${JSON.stringify(grid.generated)};`,
    `export const GRID_TEMPLATES_COMMIT = ${JSON.stringify(grid.sources?.templatesCommit ?? null)};`,
    '/** Grid model id → name, maker and licence as the grid records them. */',
    'export const GRID_MODELS: Record<string, { name: string; maker: string; openWeights: boolean; licence: string; licenceUrl: string | null }> = {',
    ...Object.entries(models).map(([k, v]) => `  ${JSON.stringify(k)}: ${j(v)},`),
    '};',
    '/** Grid feature id → grid model id → the workflow the grid credits for that pair. */',
    'export const GRID_WORKFLOWS: Record<string, Record<string, WorkflowSource>> = {',
    ...FEATURES.flatMap((f) => [`  ${JSON.stringify(f)}: {`, ...Object.entries(cells[f]).map(([k, v]) => `    ${JSON.stringify(k)}: ${j(v)},`), '  },']),
    '};',
    '',
  ];
  return lines.join('\n');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const out = render(JSON.parse(fs.readFileSync(GRID, 'utf8')));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== out) { console.error('server/src/shared/workflowSources.ts is out of date: run node scripts/gen-workflow-sources.mjs'); process.exit(1); }
    console.log('ok workflowSources.ts matches image-grid.json');
  } else { fs.writeFileSync(OUT, out); console.log(`wrote ${path.relative(ROOT, OUT)}`); }
}
