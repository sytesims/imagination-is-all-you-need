/**
 * Our parkour clips (2026-10-26): shrink the clips author.py exported and write the clip list the app reads.
 *   node pack.mjs parkour-raw.glb meta.json web/public/models/mannequin/parkour.glb web/src/shared/previz/parkourClips.ts
 * Keeps rotations of the body bones, root and pelvis translation (root = where the person stands, the root motion); drops fingers, scale and
 * the other translations (the mannequin's own lengths are used), resamples, quantizes and meshopt-compresses. Not part of the build.
 * Needs the gltf-transform packages from npm, outside the repo (as scripts/assets/optimize-mannequin.mjs).
 */
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { resample, dedup, prune, quantize, meshopt } from '@gltf-transform/functions';
import { MeshoptEncoder, MeshoptDecoder } from 'meshoptimizer';
import { readFileSync, writeFileSync } from 'node:fs';
const [src, metaFile, out, tsOut] = process.argv.slice(2);
await MeshoptEncoder.ready; await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.encoder': MeshoptEncoder, 'meshopt.decoder': MeshoptDecoder });
const doc = await io.read(src);
for (const a of doc.getRoot().listAnimations()) for (const ch of a.listChannels()) {
  const n = ch.getTargetNode()?.getName() ?? ''; const path = ch.getTargetPath();
  if (path === 'scale' || /^(index|middle|pinky|ring|thumb)_|_leaf_/.test(n) || (path === 'translation' && !/^(root|pelvis)$/.test(n))) { const sm = ch.getSampler(); ch.dispose(); sm?.dispose(); }
}
await doc.transform(prune({ keepLeaves: true }), resample({ tolerance: 2e-4 }), dedup(), prune({ keepLeaves: true }), quantize(), meshopt({ encoder: MeshoptEncoder, level: 'high' }));
await io.write(out, doc);
const meta = JSON.parse(readFileSync(metaFile, 'utf8'));
const clips = meta.map(({ props, ...c }) => ({ ...c, props: props.map(([f, u, l]) => ({ f, u, l })) }));
const ts = `/**
 * Our parkour clips (2026-10-26): the list of hand-made moves in web/public/models/mannequin/parkour.glb (our own keyframes on the Universal
 * Animation Library skeleton, CC0). GENERATED by scripts/assets/parkour/pack.mjs from scripts/assets/parkour/clips.py: change the clips there
 * and run the scripts again (see scripts/assets/parkour/README.md), don't edit this file.
 * Units: metres and frames (fps). Positions are in the person's frame at the start of the clip: f forward, u up, l to their left.
 *  - move: where the root ends up (the root motion: f, u, l); the root is the point on the ground under the person
 *  - needs: what the move is made for (obstacle kind, its height range in metres, how far ahead it starts: at)
 *  - contacts: frames of the key moments (takeoff, hands down, landing, ...)
 *  - props: the obstacle boxes the clip was keyed against (the preview page draws them)
 *  - key: the KeyboardEvent.code suggested for trying it (the actor's 1–6 are taken)
 */
export interface ParkourBox { f: [number, number]; u: [number, number]; l: [number, number] }
export interface ParkourClip { id: string; label: string; key: string; needs: Record<string, unknown>; contacts: Record<string, number | number[]>;
  frames: number; fps: number; seconds: number; move: [number, number, number]; props: ParkourBox[] }
export const PARKOUR_URL = '/models/mannequin/parkour.glb';
export const PARKOUR_CLIPS: ParkourClip[] = ${JSON.stringify(clips, null, 1).replace(/\n\s*(-?[\d.]+,?)(?=\n)/g, ' $1').replace(/\[\s+/g, '[').replace(/\s+\]/g, ']')};
`;
writeFileSync(tsOut, ts);
console.log('packed', out, clips.length, 'clips');
