#!/usr/bin/env python3
"""Writes readiness/B-RESULTS.md from manifest/models.json, manifest/custom-nodes.json and contracts/results.json.
Run after: npm run models:manifest && npm run nodes:pins && npm run contracts:test"""
import json, os, collections
R = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
M = json.load(open(f'{R}/manifest/models.json')); N = json.load(open(f'{R}/manifest/custom-nodes.json')); C = json.load(open(f'{R}/contracts/results.json'))
models = {m['file']: m for m in M['models']}; wfs = M['workflows']
cls_by_wf = collections.defaultdict(list)
for c in N['classes']:
    for w in c['workflows']: cls_by_wf[w].append(c)
E = {'green': '🟢', 'amber': '🟠', 'red': '🔴', 'n/a': '⚪'}
def wkey(w): return w if w.startswith(('workflows/', 'plugins/')) else 'workflows/' + w
def manifest_cell(ws):
    if not ws: return 'red', 'no workflow built'
    bad = [m for w in ws for m in wfs.get(wkey(w), {}).get('models', []) if models[m]['head_status'] != 'ok']
    n = len({m for w in ws for m in wfs.get(wkey(w), {}).get('models', [])})
    v = max(wfs.get(wkey(w), {}).get('vram_est_gb', 0) for w in ws); mps = [wfs.get(wkey(w), {}).get('mps', 'green') for w in ws]
    worst = 'red' if 'red' in mps else 'amber' if 'amber' in mps else 'green'
    return ('red' if bad else 'green'), f"{n} files resolve{' — BAD: ' + ', '.join(bad) if bad else ''}; VRAM ≈{v} GB; MPS {E[worst]}"
def pins_cell(ws):
    if not ws: return 'n/a', ''
    cs = {c['class']: c for w in ws for c in cls_by_wf.get(wkey(w), [])}
    custom = sorted({c['pack'] for c in cs.values() if c['pack'] != 'ComfyUI (core)'}); miss = [k for k, c in cs.items() if not c['found_in_pin']]
    return ('red' if miss else 'green'), f"{len(cs)} classes found at pin" + (f"; packs: {', '.join(custom)}" if custom else '; core only') + (f"; MISSING {miss}" if miss else '')
groups = collections.OrderedDict()
for o in C['openWeights']:
    k = (o['provider'], tuple(o['workflows'])); g = groups.setdefault(k, {'tools': [], **o}); g['tools'].append(o['tool'])
EXT = {'object-swap': ['object-swap/ext-%d.json' % i for i in range(7)], 'motion-transfer': ['motion-transfer/ext-%d.json' % i for i in range(7)]}
lines = ['# B-RESULTS: model manifest, node pins, hosted contracts', '',
 'Generated by `python3 readiness/manifest/build-b-results.py` from `manifest/models.json` (`npm run models:manifest`), `manifest/custom-nodes.json` (`npm run nodes:pins`) and `contracts/results.json` (`npm run contracts:test`). Fixtures are **hand-written from public docs**, not recorded live. No network calls to any paid API were made; HF checks are HEAD requests.', '',
 f"**Totals:** {len(M['models'])} model files, {sum(m['head_status']=='ok' for m in M['models'])} resolve, {sum(m['head_status']=='gated' for m in M['models'])} gated (HF access needed), {sum(m['head_status'] not in ('ok','gated') for m in M['models'])} unresolved. {len(N['classes'])} node classes, {sum(c['found_in_pin'] for c in N['classes'])} found by grep at their pinned commit across {len(N['packs'])} repos. {len(C['rows'])} hosted providers contract-tested: " + ', '.join(f"{sum(r['status']==s for r in C['rows'])} {s}" for s in ('green','amber','red')) + '.', '',
 '## Open-weights tools', '', '| Tool(s) | Provider | Workflows | Manifest | Node pins | Contract | Notes |', '|---|---|---|---|---|---|---|']
for (pid, ws), g in groups.items():
    ws = list(ws) + [e for t in g['tools'] for e in EXT.get(t, []) if pid == 'comfy-open']
    ms, mt = manifest_cell(ws); ps, pt = pins_cell(ws)
    note = '' if ws else ('custom node pack not built/pinned (' + ', '.join(g['nodes']) + ')' if g['nodes'] else 'no ComfyUI workflow yet; mock only') 
    if ws: note = '; '.join(sorted({n.split(' [')[0] for w in ws for n in wfs.get(wkey(w), {}).get('mps_notes', [])}))[:300]
    tools = ', '.join(sorted(set(g['tools'])))
    lines.append(f"| {tools} | `{pid}` | {', '.join(ws[:4])}{' +%d' % (len(ws)-4) if len(ws) > 4 else ''} | {E[ms]} {mt} | {E[ps]} {pt} | ⚪ n/a (local) | {note} |")
lines += ['', '## Hosted providers (partner nodes, Comfy Router, direct APIs)', '', '| Provider | Kind | Used by | Target | Contract | Checks | Notes |', '|---|---|---|---|---|---|---|']
used = collections.defaultdict(list)
for h in C['hostedTools']: used[h['provider']].append(h['tool'])
for r in C['rows']:
    t = sorted(set(used[r['id']])); 
    lines.append(f"| `{r['id']}` {r['name']} | {r['kind']} | {', '.join(t[:3])}{' +%d' % (len(t)-3) if len(t) > 3 else ''} | {r['target']} | {E[r['status']]} {r['status']} | {r['checks']} | {'; '.join(r['errors'] + r['notes'])} |")
lines += ['', '## Plugins', '']
for w, e in wfs.items():
    if w.startswith('plugins/'): ps, pt = pins_cell([w]); lines.append(f"- `{w}`: {e['total_gb']} GB, VRAM ≈{e['vram_est_gb']} GB, MPS {E[e['mps']]}; pins {E[ps]} {pt}")
lines += ['', '## Sources (VRAM / MPS)', ''] + [f"- **{k}**: {v}" for k, v in M['sources'].items()]
open(f'{R}/B-RESULTS.md', 'w').write('\n'.join(lines) + '\n'); print('wrote', f'{R}/B-RESULTS.md', len(lines), 'lines')
