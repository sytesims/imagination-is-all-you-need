import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { validateUpload } from '../src/uploadSecurity.js';
const root = path.resolve(import.meta.dirname,'../../.preview'); fs.mkdirSync(root,{recursive:true});
const dir = fs.mkdtempSync(path.join(root,'reel-jpeg-'));
const jpeg = path.join(dir,'saved-photo.jpg'), quarantine = path.join(dir,'0');
const r = spawnSync('ffmpeg',['-y','-v','error','-f','lavfi','-i','testsrc=size=960x720','-frames:v','1',jpeg]);
assert.equal(r.status,0,String(r.stderr)); fs.copyFileSync(jpeg,quarantine);
const want = {ext:'.jpg',mime:'image/jpeg',kind:'image'};
assert.deepEqual(await validateUpload(quarantine,'upload.jpg','image/jpeg','photos','image'),want,'initial quarantined JPEG');
assert.deepEqual(await validateUpload(jpeg,'library.jpg','','image','image'),want,'saved JPEG reused by child through @file:image');
assert.deepEqual(await validateUpload(jpeg,'library.jpeg','','image','image'),want,'jpeg extension alias');
await assert.rejects(()=>validateUpload(jpeg,'library.jpg','image/png','image','image'),'MIME mismatch still rejected');
const corrupt = path.join(dir,'corrupt.jpg');fs.writeFileSync(corrupt,Buffer.concat([fs.readFileSync(jpeg),Buffer.from('trailing bytes')]));
await assert.rejects(()=>validateUpload(corrupt,'corrupt.jpg','','image','image'),'signature/trailing bytes rejection unchanged');
fs.writeFileSync(corrupt,Buffer.from([255,216,255,...Array(20).fill(0),255,217]));
await assert.rejects(()=>validateUpload(corrupt,'corrupt.jpg','','image','image'),'header alone never replaces codec/decode validation');
console.log('PASS: JPEG quarantine and library validation agree; MIME, signature and decoding checks still reject damaged media');
