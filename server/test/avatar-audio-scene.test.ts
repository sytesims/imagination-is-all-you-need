/** Source contracts complement (not replace) the isolated Brave interaction/capture run. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = (name: string) => readFileSync(new URL(`../../web/src/ui/explore/${name}`, import.meta.url), 'utf8');
const wrapper = read('AvatarAudioScene.tsx');
const engine = read('avatarAudioSceneEngine.ts');
const css = read('avatarAudioScene.css');
const presenter = read('ExplorePresenter.tsx');

assert.match(wrapper, /import\('\.\/avatarAudioSceneEngine'\)/);
assert.match(wrapper, /if \(e\.isIntersecting\)[\s\S]*load\(\)/);
assert.doesNotMatch(wrapper, /import .* from 'three'/);
assert.match(wrapper, /deviceMemory <= 4/); assert.match(wrapper, /hardwareConcurrency <= 2/);
assert.match(wrapper, /connection\?\.saveData/);
assert.match(wrapper, /motion\.addEventListener\('change'/);
assert.match(wrapper, /e\.nativeEvent\.isTrusted/);
assert.match(wrapper, /children\(mode !== 'fallback'\)/, 'enhanced player is poster/manual until a native Play gesture');
assert.match(presenter, /manual=\{manual\}/);
assert.equal((presenter.match(/<ShowcaseFilm\b/g) || []).length, 1, 'reuse the original player, not a second player');
assert.doesNotMatch(wrapper + engine, /new Audio\(|createMediaElementSource\(/, 'no second audible media element or permanent reroute of the retained video');
assert.match(engine, /gain\.gain\.value = 0/);
assert.match(engine, /source\.connect\(analyser\)/);
assert.match(engine, /analyser\.connect\(gain\); gain\.connect\(context\.destination\)/);
assert.match(engine, /getByteTimeDomainData\(wave\)/);
assert.doesNotMatch(engine, /Math\.random/);
assert.match(engine, /video\.currentTime % buffer\.duration/);
assert.match(engine, /Math\.abs\(offset - predicted\) < \.12/);
for (const name of ['seeking', 'seeked', 'pause', 'ratechange', 'timeupdate']) assert.ok(engine.includes(`'${name}'`));
assert.match(engine, /new VideoTexture\(video\)/);
assert.match(engine, /1000 \/ 30/);
assert.match(engine, /Math\.min\(devicePixelRatio \|\| 1, 1\.5\)/);
assert.match(engine, /!visible \|\| document\.hidden/);
assert.match(engine, /context\.close\(\)/);
assert.match(engine, /renderer\.dispose\(\); renderer\.forceContextLoss\(\); canvas\.remove\(\)/);
assert.match(engine, /mutation\.disconnect\(\); observer\.disconnect\(\)/);
assert.match(engine, /videoTexture\?\.dispose\(\); portraitTexture\?\.dispose\(\)/);
assert.match(css, /:fullscreen \.sfilm-stage[^\{]*\{visibility:visible\}/, 'native fullscreen must not inherit a hidden stage');
assert.match(wrapper, /data-testid="avatar-scene-play"/, 'obvious keyboard/touch demo affordance');
assert.match(wrapper, /querySelector<HTMLButtonElement>\('\[data-testid="xp-presenter-film-play"\]'\)\?\.click\(\)/, 'delegate synchronously to the existing native transport');
assert.match(wrapper, /Voice clip/);
assert.match(engine, /rounded\(2\.85, \.14\)/, 'portrait/video share rounded 1:1 geometry');
assert.match(engine, /applyMatrix4\(card\.matrixWorld\)\.project\(camera\)/, 'connector attaches to the actual turning card');
assert.match(engine, /frontMaterial\.map = texture; frontMaterial\.needsUpdate = true; ready\(\)/, 'wait for portrait texture before exposing enhancement');
assert.match(css, /\.xpa-result:has\(\.aas-scene\)>\.xpa-input\{display:none\}/, 'hide duplicate thumbnail only in enhancement');
assert.match(engine, /video\.currentTime \/ \.18/, 'readable handoff settles within the first 180ms of the media clock');
assert.match(engine, /introDone \? 1/, 'loops and replay do not repeat the intro');
assert.doesNotMatch(engine, /backMaterial|scale\.setScalar|startTime|setTimeout|flip \* Math\.PI/, 'no back-face spin, scaling, new intro timer or layered face');
assert.match(engine, /frontMaterial\.map = videoTexture/, 'video uses the same front surface as the portrait');
console.log('ok avatar scene source contracts: lazy/manual, conservative fallback, trusted audio, silent real-voice analyser, native VideoTexture, sync, caps and disposal (browser evidence separate)');
